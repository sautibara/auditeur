/// Spawn a blocking closure in [`tokio`], resuming any panics from the closure if they occur
async fn spawn_blocking<F, R>(func: F) -> R
where
    F: FnOnce() -> R + Send + 'static,
    R: Send + 'static,
{
    match tokio::task::spawn_blocking(func).await {
        Err(err) => std::panic::resume_unwind(err.into_panic()),
        Ok(val) => val,
    }
}

/// Serialize `value` to the file at `path`, using [`ron`]
async fn serialize<T: Serialize + Send + Sync + 'static>(
    path: PathBuf,
    value: T,
) -> Result<(), Error> {
    spawn_blocking(move || {
        let file = std::fs::File::create(&path)?;
        ron::ser::to_writer(file, &value)
            .map_err(|error| Error::Serialization { error, file: path })?;
        Ok(())
    })
    .await
}

/// Deserialize `value` from to the file at `path`, using [`ron`]
async fn deserialize<T: for<'de> Deserialize<'de> + Send + 'static>(
    path: PathBuf,
) -> Result<T, Error> {
    spawn_blocking(move || {
        let file = std::fs::File::open(&path)?;
        let value = ron::de::from_reader(file)
            .map_err(|error| Error::Deserialization { error, file: path })?;
        Ok(value)
    })
    .await
}

/// Returns `true` if `path` exists and isn't empty
fn path_exists_with_children(path: &Path) -> Result<bool, Error> {
    Ok(path.exists() && path.is_dir() && std::fs::read_dir(path)?.next().is_some())
}

pub struct Arena {
    arena_dir: PathBuf,
    output_dir: PathBuf,
    config: config::host::Arena,
    loaded: HashMap<PluginName, LoadedPlugin>,
    binaries: HashMap<PluginName, PathBuf>,
    error_sink: ErrorSink,
}

impl Arena {
    pub async fn open_or_init(config: &config::Host) -> Self {
        let mut error_sink = ErrorSink::new();
        let arena_dir = config.directories().arena_dir();
        trace!("opening arena at '{arena_dir:?}'");
        let binaries =
            Self::deserialize_binary_file(arena_dir.join("built_binaries.ron"), &mut error_sink)
                .await;
        let mut arena = Self {
            arena_dir,
            output_dir: config.directories().plugin_dir(),
            config: config.arena.clone(),
            loaded: HashMap::new(),
            error_sink,
            binaries,
        };
        let plugins = config
            .plugins
            .iter()
            .map(|plugin| (&plugin.source, &plugin.enabled));
        let static_dependencies = config
            .static_dependencies
            .iter()
            .map(|source| (source, &config::host::Enabled::All(false)));
        let source_loads = plugins
            .chain(static_dependencies)
            .map(|(source, enabled)| async {
                arena
                    .load_source(source, enabled)
                    .await
                    .map_err(|err| (source.clone(), err))
            });
        // load each source at the same time, then add them in sequence
        // they can't all be added at the same time, as that create multiple mutable references
        for result in futures::future::join_all(source_loads).await {
            match result {
                Ok(loaded_source) => drop(arena.add_loaded_source(loaded_source)),
                Err((source, error)) => arena.error_sink.add_for_source(source, error),
            }
        }
        arena
    }

    async fn deserialize_binary_file(
        file: PathBuf,
        error_sink: &mut ErrorSink,
    ) -> HashMap<PluginName, PathBuf> {
        let binaries = if file.exists() {
            deserialize(file)
                .await
                .map_err(|err| error_sink.add_generic(err))
                .ok()
        } else {
            None
        };
        binaries.unwrap_or_default()
    }

    fn plugins(&self) -> impl Iterator<Item = &LoadedPlugin> {
        self.loaded.values()
    }

    fn enabled_plugins(&self) -> impl Iterator<Item = &LoadedPlugin> {
        self.plugins().filter(|plugin| plugin.enabled)
    }

    pub async fn add_source(
        &mut self,
        source: &Source,
        enabled: &Enabled,
    ) -> Result<Updated, Error> {
        let loaded = self.load_source(source, enabled).await?;
        Ok(self.add_loaded_source(loaded))
    }

    async fn load_source(&self, source: &Source, enabled: &Enabled) -> Result<LoadedSource, Error> {
        trace!("loading source '{}'", source);
        let (path, updated) = match &source {
            Source::Github(shorthand) => {
                self.load_git_source(shorthand.with_host("github.com"))
                    .await
            }
            Source::Gitlab(shorthand) => {
                self.load_git_source(shorthand.with_host("gitlab.com"))
                    .await
            }
            Source::Bitbucket(shorthand) => {
                self.load_git_source(shorthand.with_host("bitbucket.org"))
                    .await
            }
            Source::Builtin(binary) => {
                // there's no more processing that needs to be done, so return
                return Ok(LoadedSource::Binary(binary.clone()));
            }
            Source::Path(path) => self.load_path_source(path).await,
        }?;
        let plugins = Self::load_path(path).await?;
        // workspaces may return multiple plugins, so we have to insert all of them
        let plugins = plugins
            .into_iter()
            .map(|mut plugin| {
                plugin.enabled = enabled.get(plugin.name());
                plugin
            })
            .collect();
        trace!("found plugins: {plugins:?}");
        Ok(LoadedSource::Plugins(plugins, updated))
    }

    fn add_loaded_source(&mut self, res: LoadedSource) -> Updated {
        match res {
            LoadedSource::Binary(binary) => {
                self.binaries.insert(binary.name, binary.path);
                Updated(false)
            }
            LoadedSource::Plugins(plugins, updated) => {
                // if the source updates, then all binaries should get invalidated
                if updated.has_updated() {
                    for plugin in &plugins {
                        self.binaries.remove(plugin.name());
                    }
                }
                self.loaded.extend(
                    plugins
                        .into_iter()
                        .map(|plugin| (plugin.name().clone(), plugin)),
                );
                updated
            }
        }
    }

    async fn load_path(path: PathBuf) -> Result<Vec<LoadedPlugin>, Error> {
        let mut plugins = vec![];
        // avoid recursion by using a queue
        // (recursion with async is iffy - it requires [`Box`]ing futures)
        let mut paths = vec![path];
        while let Some(path) = paths.pop() {
            let config_path = path.join("plugin.ron");
            if !config_path.exists() {
                return Err(Error::PluginFileNotFound(config_path));
            }
            let info = deserialize::<config::Plugin>(config_path).await?;
            match info {
                config::Plugin::Single(info) => plugins.push(Self::load_plugin(path, info).await?),
                config::Plugin::Workspace(workspace) => {
                    // while we could try to load all of the paths in a workspace at the same time
                    // in an aim to improve performance, it's needlessly complex and there's a good
                    // chance that it wouldn't improve performance by much anyways: we're mostly
                    // constrainted by interacting with the disk (which can't be multithreaded) and
                    // this is a fairly quick thing to do in the scheme of the whole application
                    // anyways
                    paths.extend(workspace.paths.iter().map(|child| path.join(child)));
                }
            }
        }
        Ok(plugins)
    }

    async fn load_plugin(
        path: PathBuf,
        info: config::plugin::Single,
    ) -> Result<LoadedPlugin, Error> {
        Ok(LoadedPlugin {
            path,
            info,
            enabled: false,
        })
    }

    async fn load_git_source<'a, 'b>(
        &'a self,
        repo: HostedGitShorthandRef<'b>,
    ) -> Result<(PathBuf, Updated), Error> {
        let path = self.arena_dir.join(repo.repo());
        let updated = if !path_exists_with_children(&path)? {
            // this is a dumb amount of cloning required due to the 'static bound on spawn_blocking
            // - at times like these I wish I was using some type of structured concurrency
            let path = path.to_owned();
            let repo = repo.to_owned();
            trace!("cloning '{repo}' to '{}''", path.display());
            spawn_blocking(move || Self::clone_repository_blocking(repo, path)).await?;
            true
        } else {
            // TODO: check for updates
            false
        };
        Ok((path, Updated(updated)))
    }

    pub fn clone_repository_blocking(repo: HostedGitShorthand, path: PathBuf) -> Result<(), Error> {
        let mut callbacks = git2::RemoteCallbacks::new();
        let url = if let Ok(key) = std::env::var("AUDITEUR_SSH") {
            let key = PathBuf::from(key);
            callbacks.credentials(move |_url, user_from_url, cred_type| {
                let user_from_url = user_from_url.unwrap_or("git");
                if cred_type.contains(CredentialType::USERNAME) {
                    git2::Cred::username(user_from_url)
                } else {
                    git2::Cred::ssh_key(user_from_url, None, &key, None)
                }
            });
            repo.as_ssh()
        } else {
            repo.as_https()
        };

        let mut fo = git2::FetchOptions::new();
        fo.remote_callbacks(callbacks);

        git2::build::RepoBuilder::new()
            .fetch_options(fo)
            .clone(&url, &path)
            .map_err(|error| Error::Git { error, url })?;
        Ok(())
    }

    async fn load_path_source(&self, source: &Path) -> Result<(PathBuf, Updated), Error> {
        if !source.exists() || !source.is_dir() {
            return Err(Error::PathNotFound(source.to_owned()));
        }
        let path = source
            .file_name()
            .ok_or_else(|| Error::NoComponentsInPath(source.to_owned()))?;
        let path = self.arena_dir.join(path);
        let updated = if !path_exists_with_children(&path)? {
            trace!("copying '{}' to '{}'", source.display(), path.display());
            tokio::fs::copy(source, &path).await?;
            true
        } else {
            // TODO: check for updates
            false
        };
        Ok((path, Updated(updated)))
    }

    pub async fn build(&mut self) -> Option<BinaryList> {
        match self.maybe_build().await {
            // all plugins should be built now, so we can say that we've been built
            Ok(()) => Some(BinaryList { arena: self }),
            Err(err) => {
                self.error_sink.add_generic(err);
                None
            }
        }
    }

    async fn maybe_build(&mut self) -> Result<(), Error> {
        trace!("building arena");
        self.check_rustc().await?;
        self.create_workspace().await?;
        // TODO: clone and link the entirety of auditeur as well
        self.build_plugins().await?;
        if !self.config.retain_build_artifacts {
            self.remove_target_dir().await;
        }
        self.link_workspace_dependencies().await;
        self.serialize_built_binaries().await;
        Ok(())
    }

    async fn check_rustc(&self) -> Result<(), Error> {
        trace!("  checking rustc version");
        let expected = built_info::RUSTC_VERSION;
        let found_bytes = Command::new("rustc")
            .arg("--version")
            .output()
            .await?
            .stdout;
        let found = String::from_utf8_lossy(&found_bytes).trim().to_owned();
        if found != expected {
            Err(Error::InvalidRustc {
                found,
                expected: expected.to_owned(),
            })
        } else {
            Ok(())
        }
    }

    async fn create_workspace(&self) -> Result<(), Error> {
        trace!("  creating the cargo workspace");
        let enabled_paths: Vec<_> = self.enabled_plugins().map(|plugin| &plugin.path).collect();
        trace!("    members: {enabled_paths:?}");
        let path_list = enabled_paths
            .into_iter()
            .map(|path| path.to_string_lossy())
            .fold('\n'.to_string(), |mut string, path| {
                string.push_str(&format!("  \"{path}\",\n"));
                string
            });
        let opt_level = built_info::OPT_LEVEL;
        let debug = built_info::DEBUG;
        let workspace_toml = format!(
            r#"
[workspace]

members = [{path_list}]
resolver = "2"

[profile.auditeur]
inherits = "release"
opt-level = {opt_level}
debug = {debug}
"#
        );
        let mut file = File::create(self.arena_dir.join("Cargo.toml")).await?;
        file.write_all(workspace_toml.as_bytes()).await?;
        Ok(())
    }

    async fn build_plugins(&mut self) -> Result<(), Error> {
        trace!("building all plugins");
        let mut build_command = std::process::Command::new("cargo")
            .arg("build")
            // canaries
            .args(["--profile", "auditeur"])
            .args(["--target", built_info::TARGET])
            .args(["--jobs", &built_info::NUM_JOBS.to_string()])
            // output as json
            .arg("--message-format=json-render-diagnostics")
            .arg("--quiet") // avoid non-json messages
            // keep going even if one plugin fails to compile
            .arg("--keep-going")
            // don't compile as incremental if we're not even retaining the info
            .env(
                "CARGO_INCREMENTAL",
                (self.config.retain_build_artifacts as usize).to_string(),
            )
            // run the command at the root of the workspace
            .current_dir(&self.arena_dir)
            // pipe the stdout to this process
            .stdout(Stdio::piped())
            .spawn()?;

        let message_stream = build_command.stdout.take().expect("stdout should be piped");
        // collect the names out here so it can be given to the other thread without references
        // these are used to filter the cargo messages so that they only contain plugin artifacts
        let enabled_plugin_names: HashSet<PluginName> = self
            .enabled_plugins()
            .map(|plugin| plugin.name().clone())
            .collect();
        // parse the messages in another thread since cargo_metadata doesn't work with async
        let messages: Vec<CargoMessage> =
            spawn_blocking(move || Self::parse_messages(message_stream, enabled_plugin_names))
                .await?;
        // wait for the process to finish
        let _exit_code = spawn_blocking(move || build_command.wait()).await?;

        for message in messages {
            match message {
                // try to collect any binaries
                CargoMessage::CompilerArtifact(artifact) => {
                    self.add_compiler_artifact(artifact)?;
                }
                CargoMessage::CompilerMessage(message) => self.handle_compiler_message(message),
                _ => unreachable!(),
            }
        }

        Ok(())
    }

    fn parse_messages(
        stream: impl Read,
        names: HashSet<PluginName>,
    ) -> std::io::Result<Vec<CargoMessage>> {
        let reader = std::io::BufReader::new(stream);
        CargoMessage::parse_stream(reader)
            .filter(|message| match message {
                Ok(CargoMessage::CompilerArtifact(artifact))
                    if names.contains(&artifact.target.name) =>
                {
                    true
                }
                Ok(CargoMessage::CompilerMessage(_)) => true,
                Err(_) => true,
                _ => false,
            })
            .collect()
    }

    fn add_compiler_artifact(&mut self, artifact: cargo_metadata::Artifact) -> Result<(), Error> {
        // TODO: PluginName != Cargo.toml name
        let plugin = PluginName(artifact.target.name);
        assert!(
            self.loaded.contains_key(&plugin),
            "artifact messages should be filtered"
        );
        if let [binary] = &artifact.filenames[..] {
            self.add_binary(plugin, binary.as_std_path())?;
        } else {
            warn!(
                "incorrect number of binaries received for {plugin}. found {}, expected 1",
                artifact.filenames.len()
            )
        }
        Ok(())
    }

    fn add_binary(&mut self, name: PluginName, path: &Path) -> Result<(), Error> {
        let Some(filename) = path.file_name() else {
            warn!("recieved empty binary for {name}");
            return Ok(());
        };
        let new_path = self.output_dir.join(filename);
        std::fs::rename(path, &new_path)?;
        self.binaries.insert(name, new_path);
        trace!("  added binary '{}'", filename.to_string_lossy());
        Ok(())
    }

    fn handle_compiler_message(&mut self, message: cargo_metadata::CompilerMessage) {
        let plugin = PluginName(message.target.name.clone());
        if self.loaded.contains_key(&plugin) {
            self.error_sink.add_for_plugin(plugin, message);
        } else {
            self.error_sink.add_generic(message);
        }
    }

    async fn remove_target_dir(&mut self) {
        trace!("removing target dir");
        let target_dir_path = self.arena_dir.join("target");
        let res = tokio::fs::remove_dir_all(&target_dir_path).await;
        if let Err(err) = res {
            self.error_sink.add_generic(Error::Io(err));
        }
    }

    async fn link_workspace_dependencies(&mut self) {
        trace!("linking inner-workspace dependencies");
        for (name, res) in join_all(self.loaded.values().map(|plugin| {
            Self::link_plugin_dependencies(plugin, &self.loaded).map(|res| (plugin.name(), res))
        }))
        .await
        {
            if let Err(err) = res {
                self.error_sink.add_for_plugin(name.clone(), err);
            }
        }
    }

    async fn link_plugin_dependencies(
        plugin: &LoadedPlugin,
        loaded: &HashMap<PluginName, LoadedPlugin>,
    ) -> Result<(), Error> {
        if plugin.info.dependencies.is_empty() {
            return Ok(());
        }

        trace!("linking `{}`'s dependencies", plugin.name());
        let path = plugin.path.join("Cargo.toml");
        let manifest_path = path.clone();
        let mut manifest = spawn_blocking(move || Manifest::from_path(manifest_path))
            .await
            .map_err(|error| Error::CargoParse {
                error,
                path: path.clone(),
            })?;
        // TODO: respect version
        for dependency in plugin.info.dependencies.keys() {
            let dependency =
                loaded
                    .get(dependency)
                    .ok_or_else(|| Error::UnsatisfiedDependency {
                        for_plugin: plugin.name().clone(),
                        dependency: dependency.clone(),
                    })?;
            manifest.dependencies.insert(
                // FIXME: use cargo name
                dependency.name().clone().0,
                cargo_toml::Dependency::Detailed(Box::new(cargo_toml::DependencyDetail {
                    path: Some(path.to_string_lossy().into_owned()),
                    ..Default::default()
                })),
            );
        }
        let mut file = File::create(&path).await?;
        let serialized = spawn_blocking(move || toml::ser::to_string_pretty(&manifest))
            .await
            .map_err(|error| Error::TomlSerialization {
                error,
                path: path.clone(),
            })?;
        file.write_all(serialized.as_bytes()).await?;
        Ok(())
    }

    async fn serialize_built_binaries(&mut self) {
        let file = self.arena_dir.join("built_binaries.ron");
        // PERF: serialize requires a 'static bound from spawn_blocking to prevent a leakpocalypse
        // or something, but that prevents us using a reference to serialize
        // instead, we're forced to clone the binaries, which isn't great, but not terrible either
        let binaries = self.binaries.clone();
        if let Err(err) = serialize(file, binaries).await {
            self.error_sink.add_generic(err);
        }
    }

    pub fn errors(&self) -> &ErrorSink {
        &self.error_sink
    }
}

enum LoadedSource {
    Plugins(Vec<LoadedPlugin>, Updated),
    Binary(BinarySource),
}

pub struct BinaryList<'arena> {
    arena: &'arena mut Arena,
}

impl<'arena> BinaryList<'arena> {
    pub fn binaries(&self) -> &HashMap<PluginName, PathBuf> {
        &self.arena.binaries
    }

    pub fn enabled_binaries(&self) -> impl Iterator<Item = (&PluginName, &PathBuf)> {
        self.arena.binaries.iter().filter(|(name, _)| {
            self.arena
                .loaded
                .get(*name)
                .is_some_and(|plugin| plugin.enabled)
        })
    }

    /// # Safety
    ///
    /// The plugin system calls foreign code through the use of [dynamic linking](libloading), so
    /// it is inherently unsafe - see [`PluginRegistry::load_plugin_from_file_unchecked`] for more
    /// information. However, since the code comes from other rust code and is checked in many
    /// ways, the dynamic linking should be safe.
    pub fn add_to_registry<M: Message>(
        self,
        registry: &mut PluginRegistry<M, registry::Building<'_, M>>,
    ) {
        // code duplication is needed because with just `self.enabled_binaries() `the borrow
        // checker wouldn't be able to recognize that we're only immutably accessing
        // self.arena.binaries there, not all of self (which would conflict with self.error_sink)
        let enabled_binaries = self.arena.binaries.iter().filter(|(name, _)| {
            self.arena
                .loaded
                .get(*name)
                .is_some_and(|plugin| plugin.enabled)
        });
        for (_, binary) in enabled_binaries {
            // SAFETY: these binaries either must be builtin or built from rust projects, so they
            // should be safe to run
            let res = unsafe {
                registry.load_plugin_from_file_unchecked(self.arena.output_dir.join(binary))
            };
            if let Err(err) = res {
                self.arena.error_sink.add_generic(err);
            }
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub struct Updated(pub bool);

impl Updated {
    pub fn has_updated(&self) -> bool {
        let Updated(updated) = self;
        *updated
    }
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
struct LoadedPlugin {
    // only store the name here for ease of access
    info: config::plugin::Single,
    path: PathBuf,
    enabled: bool,
}

impl LoadedPlugin {
    fn name(&self) -> &PluginName {
        &self.info.plugin.name
    }
}
